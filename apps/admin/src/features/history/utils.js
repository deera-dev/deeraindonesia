export function presetToDates(preset) {
  const now = new Date();
  const today = now.toISOString().split("T")[0];
  if (preset === "today") return { dateFrom: today, dateTo: today };
  if (preset === "week") {
    const d = new Date(now);
    d.setDate(d.getDate() - 6);
    return { dateFrom: d.toISOString().split("T")[0], dateTo: today };
  }
  if (preset === "month") {
    const d = new Date(now);
    d.setDate(d.getDate() - 29);
    return { dateFrom: d.toISOString().split("T")[0], dateTo: today };
  }
  return { dateFrom: null, dateTo: null };
}

export function formatTime(iso) {
  if (!iso) return "";
  return new Date(iso).toLocaleTimeString("id-ID", { hour: "2-digit", minute: "2-digit" });
}

export function formatGroupDate(iso) {
  if (!iso) return "";
  const d = new Date(iso);
  const now = new Date();
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  const itemDay = new Date(d.getFullYear(), d.getMonth(), d.getDate());
  const diff = (today - itemDay) / 86400000;
  if (diff === 0) return "Hari Ini";
  if (diff === 1) return "Kemarin";
  return d.toLocaleDateString("id-ID", {
    weekday: "long",
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}

export function groupByDate(items) {
  const groups = [];
  let lastKey = null;
  for (const item of items) {
    const key = new Date(item.changed_at).toLocaleDateString("id-ID");
    if (key !== lastKey) {
      groups.push({ key, label: formatGroupDate(item.changed_at), items: [] });
      lastKey = key;
    }
    groups[groups.length - 1].items.push(item);
  }
  return groups;
}

const SKIP_KEYS = new Set(["id", "created_at", "updated_at", "position", "detail", "image", "video", "foto"]);
const KEY_LABEL = {
  nama: "Nama",
  bahan: "Bahan",
  hpp: "HPP",
  harga: "Harga",
  warna: "Warna",
  variants: "Varian",
  status: "Status",
  catatan: "Catatan",
  total: "Total",
  total_hpp: "HPP",
  qty: "Qty",
  notes: "Catatan",
};

function fmtVal(v) {
  if (v == null || v === "") return "kosong";
  if (Array.isArray(v)) return `${v.length} item`;
  if (typeof v === "object") return "diubah";
  if (typeof v === "number") return v.toLocaleString("id-ID");
  const s = String(v);
  return s.length > 24 ? `${s.slice(0, 24)}…` : s;
}

export function summarizeHistory(item) {
  const before = item?.before_snapshot;
  const after = item?.snapshot;
  const isObj = (o) => o && typeof o === "object" && !Array.isArray(o);

  if (isObj(before) && isObj(after)) {
    const keys = Object.keys(after).filter(
      (k) => !SKIP_KEYS.has(k) && JSON.stringify(before[k]) !== JSON.stringify(after[k]),
    );
    if (keys.length === 0) return "";
    const parts = keys.slice(0, 3).map((k) => {
      const label = KEY_LABEL[k] ?? k.replace(/_/g, " ");
      const a = after[k];
      if (Array.isArray(a) || (a && typeof a === "object")) return `${label} diubah`;
      return `${label}: ${fmtVal(before[k])} → ${fmtVal(a)}`;
    });
    if (keys.length > 3) parts.push(`+${keys.length - 3} lainnya`);
    return parts.join(" · ");
  }

  if (isObj(after)) {
    const parts = [];
    const no = after.transfer_no ?? after.batch_no ?? after.nomor;
    if (no) parts.push(String(no));
    if (after.from_location && after.to_location) parts.push(`${after.from_location} → ${after.to_location}`);
    if (Array.isArray(after.items)) {
      const qty = after.items.reduce((n, i) => n + (Number(i?.qty ?? i?.jumlah) || 0), 0);
      parts.push(qty ? `${after.items.length} baris · ${qty} pcs` : `${after.items.length} item`);
    }
    if (after.total_kain) parts.push(`${after.total_kain} potong`);
    if (after.total_hpp) parts.push(`HPP Rp ${Number(after.total_hpp).toLocaleString("id-ID")}`);
    if (after.hpp_per_item) parts.push(`Rp ${Number(after.hpp_per_item).toLocaleString("id-ID")}/baju`);
    if (after.bahan && !parts.length) parts.push(String(after.bahan));
    if (after.catatan || after.notes) parts.push(String(after.catatan ?? after.notes).slice(0, 40));
    return parts.slice(0, 4).join(" · ");
  }
  return "";
}
